function svgFallback(label: string, cat: string, idx: number): string {
  const [from, to] = CATEGORY_PALETTES[cat] ?? ["#E5E1DA", "#C6C0B4"];
  const dirs = [
    'x1="0" y1="0" x2="1" y2="1"',
    'x1="1" y1="0" x2="0" y2="1"',
    'x1="0" y1="1" x2="1" y2="0"',
  ];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="800" viewBox="0 0 800 800"><defs><linearGradient id="g" ${dirs[idx % 3]}><stop offset="0" stop-color="${from}"/><stop offset="1" stop-color="${to}"/></linearGradient></defs><rect width="800" height="800" fill="url(#g)"/><rect x="250" y="230" width="300" height="300" rx="28" fill="rgba(255,255,255,0.35)"/><rect x="290" y="270" width="220" height="220" rx="16" fill="rgba(255,255,255,0.45)"/><text x="400" y="620" font-size="38" text-anchor="middle" fill="rgba(40,40,40,0.75)" font-family="Tahoma, Vazirmatn, sans-serif" font-weight="bold" direction="rtl">${xmlEscape(label)}</text></svg>`;
  return `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
}

function imagesFor(cat: string, name: string, productIndex: number): string[] {
  const pool = imagePools?.[cat] ?? [];
  const out: string[] = [];
  const count = 4;
  for (let k = 0; k < count; k++) {
    if (pool.length > 0) {
      out.push(pool[(productIndex + k) % pool.length]);
    } else {
      out.push(svgFallback(name, cat, k));
    }
  }
  return out;
}

