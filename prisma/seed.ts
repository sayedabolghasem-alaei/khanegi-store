function hashPassword(password: string): string {
  const salt = crypto.randomBytes(16).toString("hex");
  const hash = crypto.scryptSync(password, salt, 64).toString("hex");
  return `scrypt$${salt}$${hash}`;
}

function jalaliParts(d: Date): { y: number; m: number; day: number } {
  const fmt = new Intl.DateTimeFormat("en-u-ca-persian-nu-latn", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    timeZone: "Asia/Tehran",
  });
  const parts = fmt.formatToParts(d);
  const get = (t: string) => Number(parts.find((p) => p.type === t)?.value ?? 0);
  return { y: get("year"), m: get("month"), day: get("day") };
}

function orderNumberFor(d: Date, salt: string): string {
  const { y, m, day } = jalaliParts(d);
  const rand = crypto.randomBytes(2).toString("hex").toUpperCase();
  return `ARI-${y}${String(m).padStart(2, "0")}${String(day).padStart(2, "0")}-${salt || rand}`;
}

function daysAgo(n: number): Date {
  return new Date(Date.now() - n * 24 * 60 * 60 * 1000);
}

/** Same formula as the pricing engine (global rule: margin 12%, step 100,000). */
const USD_RATE = 115000;
function priceFromCost(costUsd: number): number {
  const raw = costUsd * USD_RATE * 1.12;
  return Math.round(raw / 100000) * 100000;
}

function xmlEscape(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

